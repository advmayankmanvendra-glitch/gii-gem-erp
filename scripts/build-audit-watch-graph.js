// build-audit-watch-graph.js — writes the Audit Watch check catalogue into AG-1.
//
// Source of truth: src/main/services/auditWatch/catalogue.js
// Output:          src/renderer/knowledge/audit-graph.json  (detectiveControls section)
//                  docs/manuals/GII-GeM-ERP-Audit-Watch-Guide.md (KG-5 manual, generated)
// Usage:           node scripts/build-audit-watch-graph.js
// Validation:      npm run verify:audit-watch
//
// Only the detectiveControls section (the last key of AG-1) is rewritten; every other
// AG-1 section is left exactly as it is, byte for byte.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = resolve(import.meta.dirname, "..");
const GRAPH = join(ROOT, "src/renderer/knowledge/audit-graph.json");
const MANUAL = join(ROOT, "docs/manuals/GII-GeM-ERP-Audit-Watch-Guide.md");
const catalogue = await import(pathToFileURL(join(ROOT, "src/main/services/auditWatch/catalogue.js")).href);

export function detectiveControlsFromCatalogue({ CHECKS, AUDIT_WATCH_VERSION, AREAS, AREA_VISIBILITY }) {
  return {
    catalogueVersion: AUDIT_WATCH_VERSION,
    source: "src/main/services/auditWatch/catalogue.js",
    manual: "docs/manuals/GII-GeM-ERP-Audit-Watch-Guide.md",
    mode: "read-only",
    counts: {
      checks: CHECKS.length,
      runnableNow: CHECKS.filter((check) => check.readiness === "now").length,
      waitingForAcc: CHECKS.filter((check) => check.readiness === "after_acc").length
    },
    areas: AREAS.map((area) => ({ ...area })),
    visibility: Object.fromEntries(Object.entries(AREA_VISIBILITY).map(([role, areas]) => [role, [...areas]])),
    checks: CHECKS.map((check) => ({
      checkId: check.id,
      area: check.area,
      title: check.title,
      severity: check.severity,
      readiness: check.readiness,
      version: check.version,
      scope: check.scope,
      ...(check.helpers ? { helpers: [...check.helpers] } : {}),
      ...(check.coverage ? { coverage: [...check.coverage] } : {}),
      ...(check.uncovered ? { uncovered: { ...check.uncovered } } : {}),
      ...(check.waitsFor ? { waitsFor: { ...check.waitsFor } } : {}),
      reads: Object.entries(check.reads).map(([table, columns]) => ({ table, columns: [...columns] })),
      limits: Object.entries(check.limits).map(([key, limit]) => ({ key, ...limit })),
      meaning: check.meaning,
      nextStep: check.nextStep
    }))
  };
}

const UNIT_TEXT = { days: "days", percent: "%", rupees: "rupees", count: "", time: "IST" };

function limitText(limit) {
  if (limit.unit === "rupees") return `Rs. ${Number(limit.default).toLocaleString("en-IN")}`;
  const unit = UNIT_TEXT[limit.unit] ?? limit.unit;
  return unit === "%" ? `${limit.default}%` : `${limit.default}${unit ? ` ${unit}` : ""}`;
}

// The KG-5 manual. Generated so the screen, the graph and the manual use one wording.
export function manualFromCatalogue({ CHECKS, AREAS, AREA_VISIBILITY, AUDIT_WATCH_VERSION }) {
  const lines = [
    "# GII GeM ERP — Audit Watch Guide",
    "",
    `<!-- Generated by scripts/build-audit-watch-graph.js from src/main/services/auditWatch/catalogue.js (catalogue ${AUDIT_WATCH_VERSION}). Do not edit by hand. -->`,
    "",
    "## What Audit Watch Does",
    "",
    "Audit Watch looks through one company's books and lists exceptions that an internal auditor or CA should look at: duplicate bills, a payment soon after a supplier's bank account changed, a journal keyed on a Sunday, an admin account nobody uses.",
    "",
    "It only reads. It never posts, edits or reverses anything, and nothing leaves this computer. Every check is a plain rule or a simple count, so each finding shows the rows behind it and can be explained.",
    "",
    "Reversed bills, payments and sales bills are not counted: reversing a wrong entry and keying it again is a normal correction, not a duplicate. Checks on users and the audit trail look at the whole installation, because users are shared by every company on the computer.",
    "",
    "## How to Read a Finding",
    "",
    "A finding is an exception to look at, not proof that anything is wrong. Each one shows what was seen, the records behind it and a suggested next step. Many findings have an innocent reason; record that reason so the next reviewer does not repeat the work.",
    "",
    "Severity: **high** means money could leave the business or the books may be wrong; **medium** needs a look this month; **low** is housekeeping.",
    "",
    "## Who Sees Audit Watch",
    "",
    ...Object.entries(AREA_VISIBILITY).map(([role, areas]) => `- ${role.replaceAll("_", " ")}: ${areas.length ? areas.map((id) => AREAS.find((area) => area.id === id).label).join(", ") : "no access"}`),
    "",
    "Data entry operators and viewers do not see Audit Watch, because a finding may be about their own work.",
    ""
  ];
  for (const area of AREAS) {
    lines.push(`## ${area.label}`, "");
    for (const check of CHECKS.filter((item) => item.area === area.id)) {
      lines.push(`### ${check.id} ${check.title}`, "");
      const scope = check.scope === "installation" ? " Looks at the whole installation, not only one company." : "";
      lines.push(`Severity: ${check.severity}.${scope}${check.readiness === "now" ? "" : " Not run yet: waits for the accounting programme (ACC) to reach the main build."}`, "");
      lines.push(`**What it means.** ${check.meaning}`, "");
      lines.push(`**What to do.** ${check.nextStep}`, "");
      if (check.coverage?.length) lines.push(`**Looks at:** ${check.coverage.join("; ")}.`, "");
      const limits = Object.values(check.limits);
      if (limits.length) {
        lines.push("**Limits** (defaults; changing them for one company comes in a later phase):", "");
        for (const limit of limits) lines.push(`- ${limit.label}: ${limitText(limit)}`);
        lines.push("");
      }
    }
  }
  lines.push("## Payroll Checks", "", "Checks on salaries, pay after exit and employee claims will come with the payroll module.", "");
  return lines.join("\n");
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename);
if (isMain) {
  // Splice the section in as text so the rest of AG-1 keeps its hand-written layout.
  const MARKER = ',\n  "detectiveControls": ';
  let text = readFileSync(GRAPH, "utf8");
  const at = text.indexOf(MARKER);
  if (at >= 0) text = `${text.slice(0, at)}\n}\n`;
  const body = text.replace(/\n\}\s*$/, "");
  const section = detectiveControlsFromCatalogue(catalogue);
  const json = JSON.stringify(section, null, 2).replace(/\n/g, "\n  ");
  const next = `${body}${MARKER}${json}\n}\n`;
  JSON.parse(next);
  writeFileSync(GRAPH, next);
  writeFileSync(MANUAL, manualFromCatalogue(catalogue));
  console.log(`AG-1 detectiveControls: ${section.counts.checks} checks written (${section.counts.runnableNow} runnable now).`);
}
